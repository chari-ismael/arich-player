function detectLang() {
  try {
    const q = new URLSearchParams(window.location.search).get('lang')
    if (q === 'fr' || q === 'en') return q
  } catch {
    /* ignore */
  }
  const saved = localStorage.getItem('arich_lang')
  if (saved === 'fr' || saved === 'en') return saved
  const nav = (navigator.language || 'en').toLowerCase()
  return nav.startsWith('fr') ? 'fr' : 'en'
}

let lang = detectLang()

export function getLang() {
  return lang
}

export function t(key) {
  return dict[lang][key] ?? dict.en[key] ?? key
}

export function formatMoney(amount, currency = 'EUR') {
  try {
    return new Intl.NumberFormat(lang === 'fr' ? 'fr-FR' : 'en-GB', {
      style: 'currency',
      currency,
      maximumFractionDigits: 0,
    }).format(amount)
  } catch {
    return `${amount} €`
  }
}

export function formatDate(date = new Date()) {
  return new Intl.DateTimeFormat(lang === 'fr' ? 'fr-FR' : 'en-GB', {
    dateStyle: 'medium',
  }).format(date)
}

export function setLang(next) {
  lang = next === 'fr' ? 'fr' : 'en'
  localStorage.setItem('arich_lang', lang)
  document.documentElement.lang = lang
  applyI18n()
  window.dispatchEvent(new CustomEvent('arich:lang', { detail: lang }))
}

export function applyI18n() {
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n')
    const val = t(key)
    if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
      el.placeholder = val
    } else {
      el.textContent = val
    }
  })
  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    el.setAttribute('placeholder', t(el.getAttribute('data-i18n-placeholder')))
  })
  document.querySelectorAll('[data-i18n-html]').forEach((el) => {
    el.innerHTML = t(el.getAttribute('data-i18n-html'))
  })
  document.querySelectorAll('[data-lang-btn]').forEach((btn) => {
    btn.classList.toggle('is-on', btn.getAttribute('data-lang-btn') === lang)
  })
}

export function initI18n() {
  document.documentElement.lang = lang
  applyI18n()
  document.querySelectorAll('[data-lang-btn]').forEach((btn) => {
    btn.addEventListener('click', () => setLang(btn.getAttribute('data-lang-btn')))
  })
}
